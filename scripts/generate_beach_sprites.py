def hex_to_rgba(value):
    if value is None:
        return (0, 0, 0, 0)
    value = value.lstrip("#")
    return (
        int(value[0:2], 16),
        int(value[2:4], 16),
        int(value[4:6], 16),
        255,
    )


def render_sprite(rows):
    if len(rows) != H:
        raise ValueError(f"Expected {H} rows, got {len(rows)}")
    image = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    pixels = image.load()
    for y, row in enumerate(rows):
        if len(row) != W:
            raise ValueError(f"Row {y} has width {len(row)}, expected {W}")
        for x, symbol in enumerate(row):
            if symbol not in COLORS:
                raise ValueError(f"Unknown color symbol '{symbol}' at ({x}, {y})")
            pixels[x, y] = hex_to_rgba(COLORS[symbol])
    return image


def main():
    output_dir = Path(__file__).resolve().parents[1] / "assets" / "beach"
    output_dir.mkdir(parents=True, exist_ok=True)

    for name, rows in SPRITES.items():
        path = output_dir / f"{name}.png"
        render_sprite(rows).save(path)
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
